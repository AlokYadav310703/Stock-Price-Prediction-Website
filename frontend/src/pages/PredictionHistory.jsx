import React, { useMemo, useState } from 'react'
import { api } from '../services/api'
import { useAsync } from '../hooks/useAsync'
import {
  PageHeader,
  Panel,
  LoadingState,
  ErrorState,
  EmptyState,
  DirectionTag,
  ResultTag,
  fmtUSD,
} from '../components/ui'

const PAGE_SIZE = 20

export default function PredictionHistory() {
  const { data, loading, error, reload } = useAsync(() => api.getPredictions({ limit: 100000 }), [])
  const [page, setPage] = useState(0)
  const [filter, setFilter] = useState('all') // all | correct | incorrect | pending

  const filtered = useMemo(() => {
    if (!data) return []
    if (filter === 'correct') return data.filter((r) => r.is_correct === true)
    if (filter === 'incorrect') return data.filter((r) => r.is_correct === false)
    if (filter === 'pending') return data.filter((r) => r.is_correct === null)
    return data
  }, [data, filter])

  if (loading) return <LoadingState label="Loading prediction history…" />
  if (error) return <ErrorState message={error} onRetry={reload} />
  if (!data || data.length === 0) return <EmptyState title="No predictions yet" message="Insufficient data." />

  const totalPages = Math.max(1, Math.ceil(filtered.length / PAGE_SIZE))
  const pageRows = filtered.slice(page * PAGE_SIZE, page * PAGE_SIZE + PAGE_SIZE)

  const setFilterAndReset = (f) => {
    setFilter(f)
    setPage(0)
  }

  return (
    <div>
      <PageHeader
        eyebrow={`${data.length} total predictions`}
        title="Prediction History"
        description="Every prediction ever generated by the model, stored permanently — no records are overwritten."
        right={
          <div className="flex gap-1 bg-ink-800 border border-ink-600 rounded-lg p-1">
            {[
              ['all', 'All'],
              ['correct', 'Correct'],
              ['incorrect', 'Incorrect'],
              ['pending', 'Pending'],
            ].map(([key, label]) => (
              <button
                key={key}
                onClick={() => setFilterAndReset(key)}
                className={`text-xs font-medium px-3 py-1.5 rounded-md transition-colors ${
                  filter === key ? 'bg-accent-dim text-paper border border-accent/40' : 'text-paper-dim hover:text-paper'
                }`}
              >
                {label}
              </button>
            ))}
          </div>
        }
      />

      <Panel>
        {pageRows.length === 0 ? (
          <EmptyState title="No matching predictions" message="Try a different filter." />
        ) : (
          <div className="overflow-x-auto -mx-5 px-5">
            <table className="w-full text-sm min-w-[760px]">
              <thead>
                <tr className="text-left text-xs text-paper-dim uppercase tracking-wide border-b border-ink-600">
                  <th className="py-2 pr-4 font-medium">Prediction Date</th>
                  <th className="py-2 pr-4 font-medium">Target Date</th>
                  <th className="py-2 pr-4 font-medium">Predicted</th>
                  <th className="py-2 pr-4 font-medium">Actual</th>
                  <th className="py-2 pr-4 font-medium">Abs. Error</th>
                  <th className="py-2 pr-4 font-medium">Direction</th>
                  <th className="py-2 pr-4 font-medium">Result</th>
                  <th className="py-2 pr-4 font-medium">Model</th>
                </tr>
              </thead>
              <tbody>
                {pageRows.map((r) => (
                  <tr key={r.id} className="border-b border-ink-600/60 last:border-0">
                    <td className="py-2.5 pr-4 num text-paper-dim">{r.prediction_date}</td>
                    <td className="py-2.5 pr-4 num text-paper-dim">{r.target_date}</td>
                    <td className="py-2.5 pr-4 num text-paper">{fmtUSD(r.predicted_price)}</td>
                    <td className="py-2.5 pr-4 num text-paper">{r.actual_price != null ? fmtUSD(r.actual_price) : '—'}</td>
                    <td className="py-2.5 pr-4 num text-paper-dim">{r.absolute_error != null ? r.absolute_error : '—'}</td>
                    <td className="py-2.5 pr-4">
                      <DirectionTag direction={r.predicted_direction} />
                    </td>
                    <td className="py-2.5 pr-4">
                      <ResultTag isCorrect={r.is_correct} />
                    </td>
                    <td className="py-2.5 pr-4 num text-xs text-paper-dim">{r.model_version}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}

        <div className="flex items-center justify-between mt-4 pt-4 border-t border-ink-600">
          <span className="text-xs text-paper-dim">
            Showing {filtered.length === 0 ? 0 : page * PAGE_SIZE + 1}–{Math.min((page + 1) * PAGE_SIZE, filtered.length)} of{' '}
            {filtered.length}
          </span>
          <div className="flex gap-2">
            <button
              disabled={page === 0}
              onClick={() => setPage((p) => Math.max(0, p - 1))}
              className="text-xs font-medium px-3 py-1.5 rounded-md bg-ink-700 hover:bg-ink-600 disabled:opacity-40 disabled:cursor-not-allowed text-paper transition-colors"
            >
              Previous
            </button>
            <button
              disabled={page >= totalPages - 1}
              onClick={() => setPage((p) => Math.min(totalPages - 1, p + 1))}
              className="text-xs font-medium px-3 py-1.5 rounded-md bg-ink-700 hover:bg-ink-600 disabled:opacity-40 disabled:cursor-not-allowed text-paper transition-colors"
            >
              Next
            </button>
          </div>
        </div>
      </Panel>
    </div>
  )
}
